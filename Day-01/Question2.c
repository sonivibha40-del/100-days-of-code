//Write a program to input two numbers and display their sum, difference, product>
#include<stdio.h>
int main(){
   int a,b;
   printf("Enter your first no.: ");
   scanf("%d",&a);
   printf("Enter your second no.: ");
   scanf("%d",&b);
   printf("sum: %d\n",a+b);
   printf("diff: %d\n",a-b);
   printf("product: %d\n",a*b);
   printf("divide: %d\n",a/b);
   return 0;
}
